"""Keeps AeroFlux translations in one place and hands them to all six builds.

English (en_us) is generated by each build's datagen, so it is never edited by hand. Translations
live in the repo's top-level lang/ folder, one <locale>.json per language, and this script:

  python assets-src/tools/lang_sync.py export    writes lang/en_us.json, every key any build uses
  python assets-src/tools/lang_sync.py check     lists missing, unknown and broken keys per language
  python assets-src/tools/lang_sync.py install   copies each translation into every build's resources

"check" exits with 1 when a translation has a key the mod does not use or a line whose %s
placeholders do not match the English one; missing keys are only listed, since the game falls back
to English for them. "install" copies each build only the keys that build has, so a key that exists
on 26.1 alone never reaches 1.20.1.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
LANG = ROOT / "lang"
BUILDS = sorted(p for p in (ROOT / "versions").glob("mc*/*") if (p / "build.gradle").exists())
GENERATED = "src/generated/resources/assets/aeroflux/lang/en_us.json"
INSTALLED = "src/main/resources/assets/aeroflux/lang"
PLACEHOLDER = re.compile(r"%(?:\d+\$)?[sd]")


def load(path):
    return json.loads(path.read_text(encoding="utf-8"))


def write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")


def english_per_build():
    """Each build's generated English, by build folder."""
    found = {}
    for build in BUILDS:
        file = build / GENERATED
        if not file.exists():
            sys.exit(f"{file} is missing: run datagen in {build.relative_to(ROOT)} first")
        found[build] = load(file)
    return found


def english():
    """Every key any build uses, with its English text (the newest build wins on a clash)."""
    merged = {}
    for keys in english_per_build().values():
        merged.update(keys)
    return merged


def translations():
    return {path.stem: load(path) for path in sorted(LANG.glob("*.json")) if path.stem != "en_us"}


def placeholders(text):
    return sorted(PLACEHOLDER.findall(text))


def export():
    write(LANG / "en_us.json", english())
    print(f"wrote {(LANG / 'en_us.json').relative_to(ROOT)} ({len(english())} keys)")


def check():
    reference = english()
    broken = False
    for locale, keys in translations().items():
        missing = sorted(set(reference) - set(keys))
        unknown = sorted(set(keys) - set(reference))
        mismatched = sorted(key for key in set(keys) & set(reference)
                            if placeholders(keys[key]) != placeholders(reference[key]))
        done = 100 * (len(reference) - len(missing)) // max(1, len(reference))
        print(f"{locale}: {done}% translated, {len(missing)} missing, {len(unknown)} unknown, {len(mismatched)} with wrong placeholders")
        for key in unknown:
            print(f"  unknown key: {key}")
        for key in mismatched:
            print(f"  placeholders differ: {key}")
        broken |= bool(unknown or mismatched)
    if not translations():
        print("no translations in lang/ yet")
    return 1 if broken else 0


def install():
    per_build = english_per_build()
    for locale, keys in translations().items():
        for build, own in per_build.items():
            kept = {key: text for key, text in keys.items() if key in own}
            write(build / INSTALLED / f"{locale}.json", kept)
        print(f"{locale}: installed into {len(per_build)} builds")


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else "check"
    if command == "export":
        export()
    elif command == "check":
        sys.exit(check())
    elif command == "install":
        install()
    else:
        sys.exit(__doc__)
